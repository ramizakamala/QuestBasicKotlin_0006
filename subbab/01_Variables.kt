fun main() {
    // variabel read-only dengan val
    val nama = "Kotlin"
    val versi = "2.4.20"

    // variabel yang dapat diubah dengan var
    var jumlahBaris = 5

    // untuk menetapkan nilai, gunakan operator penugasan =
    jumlahBaris = jumlahBaris + 2

    println(nama)
    println(versi)
    println(jumlahBaris)
}
